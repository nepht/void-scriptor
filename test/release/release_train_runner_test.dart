import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// Sprint 102 / C6 — release-train runner.
///
/// Guarded generator: only executes when RUN_RELEASE_TRAIN=1 (same pattern
/// as the baseline generator). Verifies that the produced manifest carries
/// the REAL measured checksum and size of the built artifact.
void main() {
  test('release train produces a measured artifact manifest', () async {
    if (Platform.environment['RUN_RELEASE_TRAIN'] != '1') {
      return; // guard: plain `flutter test` must stay fast
    }
    final version = Platform.environment['RELEASE_VERSION'];
    expect(version, isNotNull, reason: 'RELEASE_VERSION must be set');

    final doc = File('docs/release/v$version-artifact-manifest.md');
    expect(doc.existsSync(), true, reason: 'train must write the manifest');

    final content = doc.readAsStringSync();
    expect(content, contains('Status: GENERATED by release-train tooling'));

    final sha = RegExp(r'SHA-256 \| `([0-9a-f]{64})`').firstMatch(content);
    expect(sha, isNotNull, reason: 'manifest must carry a measured SHA-256');

    // Cross-check against the actual built binary on disk via the same OS
    // tool used for the locked v1.0.1 manifest.
    final bin = File('build/linux/x64/debug/bundle/void_scriptor');
    expect(bin.existsSync(), true);
    final proc = await Process.run('sha256sum', [bin.path]);
    expect(proc.exitCode, 0);
    final digest = (proc.stdout as String).trim().split(' ').first;
    expect(
      sha!.group(1),
      equals(digest),
      reason: 'manifest checksum must equal the real artifact',
    );
    expect(content, contains('| Artifact size | ${bin.lengthSync()} bytes |'));
  });
}
