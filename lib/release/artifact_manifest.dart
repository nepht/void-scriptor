/// Sprint 102 / C6 — typed artifact manifest for the release train.
///
/// The Markdown renderer is deterministic and reproduces the LOCKED
/// v1.0.1 contract shape (docs/release/v1.0.1-artifact-manifest.md),
/// so RC manifests are generated from measured values instead of being
/// hand-edited.
library;

/// One validation gate row of the evidence table.
class ManifestGate {
  const ManifestGate({required this.name, required this.result});

  final String name;
  final String result;
}

/// Measured facts about one release-candidate artifact.
class ArtifactManifest {
  const ArtifactManifest({
    required this.release,
    required this.candidate,
    required this.commitSha,
    required this.tagObjectSha,
    required this.platform,
    required this.architecture,
    required this.buildMode,
    required this.buildCommand,
    required this.artifactPath,
    required this.artifactSizeBytes,
    required this.sha256,
  });

  final String release;
  final String candidate;
  final String commitSha;
  final String tagObjectSha;
  final String platform;
  final String architecture;
  final String buildMode;
  final String buildCommand;
  final String artifactPath;
  final int artifactSizeBytes;
  final String sha256;

  /// Renders the manifest in the locked-contract layout. Deterministic:
  /// identical inputs always produce byte-identical output.
  String toMarkdown({List<ManifestGate> gates = const []}) {
    final b = StringBuffer()
      ..writeln('# $release Artifact Manifest')
      ..writeln()
      ..writeln(
        'Status: GENERATED by release-train tooling — diukur dari build '
        'nyata, bukan nilai historis.',
      )
      ..writeln()
      ..writeln('## Candidate artifact')
      ..writeln()
      ..writeln('| Field | Value |')
      ..writeln('|---|---|')
      ..writeln('| Release | `$release` |')
      ..writeln('| Candidate | `$candidate` |')
      ..writeln('| Commit SHA | `$commitSha` |')
      ..writeln('| Tag object | `$tagObjectSha` |')
      ..writeln('| Platform | $platform |')
      ..writeln('| Architecture | $architecture |')
      ..writeln('| Build mode | $buildMode |')
      ..writeln('| Build command | `$buildCommand` |')
      ..writeln('| Artifact path | `$artifactPath` |')
      ..writeln('| Artifact size | $artifactSizeBytes bytes |')
      ..writeln('| SHA-256 | `$sha256` |')
      ..writeln(
        '| Signature | NOT AVAILABLE — signing infrastructure not in scope |',
      )
      ..writeln(
        '| SBOM | NOT AVAILABLE — production artifact pipeline not in scope |',
      )
      ..writeln()
      ..writeln('## Validation evidence pada commit yang sama')
      ..writeln()
      ..writeln('| Gate | Result |')
      ..writeln('|---|---|');
    for (final g in gates) {
      b.writeln('| `${g.name}` | ${g.result} |');
    }
    b
      ..writeln()
      ..writeln('## Not covered')
      ..writeln()
      ..writeln(
        'Jangan mengganti nilai terukur tanpa membangun ulang artefak dan '
        'menghitung ulang checksum.',
      );
    return b.toString();
  }
}
